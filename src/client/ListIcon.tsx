export function ListIcon({
  iconKey,
  ...props
}: LucideProps & { iconKey?: string | null }) {
  const Icon =
    iconKey && Object.hasOwn(icons, iconKey)
      ? icons[iconKey as ListIconKey]
      : ListChecks;
  return <Icon aria-hidden="true" {...props} />;
}
